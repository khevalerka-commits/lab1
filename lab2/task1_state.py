# Задание 1. Исследование изменения состояния переменной x.
x = 10
print("Шаг 1: x = 10        -> x =", x)
x = x + 5
print("Шаг 2: x = x + 5     -> x =", x)
x = x * 2
print("Шаг 3: x = x * 2     -> x =", x)
x = x - 8
print("Шаг 4: x = x - 8     -> x =", x)
x = x // 2
print("Шаг 5: x = x // 2    -> x =", x)
print("Итог:", x)
